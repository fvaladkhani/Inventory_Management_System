const fs = require('fs');
const path = require('path');

const FONT_DIR = path.join(__dirname, '..', 'public', 'fonts');
const OUTPUT_DIR = path.join(__dirname, '..', 'src', 'utils', 'fonts');
const OUTPUT_FILE = path.join(OUTPUT_DIR, 'vazirFontBase64.js');

function fontToBase64(filename) {
  const filePath = path.join(FONT_DIR, filename);
  if (!fs.existsSync(filePath)) {
    throw new Error('Font file not found: ' + filePath);
  }
  const fileBuffer = fs.readFileSync(filePath);
  return fileBuffer.toString('base64');
}

function main() {


  const regularBase64 = fontToBase64('Vazirmatn-Regular.ttf');
  const boldBase64 = fontToBase64('Vazirmatn-Bold.ttf');

  const fileContent =
    "// Auto-generated by scripts/generateFontBase64.js\n" +
    "// Do not edit manually.\n\n" +
    "export const VazirRegularBase64 = '" + regularBase64 + "';\n" +
    "export const VazirBoldBase64 = '" + boldBase64 + "';\n";

  if (!fs.existsSync(OUTPUT_DIR)) {
    fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  }

  fs.writeFileSync(OUTPUT_FILE, fileContent, 'utf8');

}

main();